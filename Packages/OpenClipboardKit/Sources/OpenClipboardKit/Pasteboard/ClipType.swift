import Foundation
import UniformTypeIdentifiers

/// The pasteboard type identifiers OpenClipboard treats specially.
public enum ClipType {
    public static let plainText = "public.utf8-plain-text"
    public static let utf16ExternalText = "public.utf16-external-plain-text"
    public static let utf16Text = "public.utf16-plain-text"
    public static let rtf = "public.rtf"
    public static let rtfd = "com.apple.flat-rtfd"
    public static let html = "public.html"
    public static let url = "public.url"
    public static let fileURL = "public.file-url"
    public static let png = "public.png"
    public static let tiff = "public.tiff"
    public static let pdf = "com.adobe.pdf"

    /// Added to everything OpenClipboard itself puts on the pasteboard. It holds the id of
    /// the clip, so the watcher moves that clip to the front instead of capturing a copy.
    public static let ownClip = "com.burakgon.OpenClipboard.clip"

    /// Markers from nspasteboard.org that ask clipboard managers to stay away: content that
    /// is only on the pasteboard for a moment, or that an app generated on its own.
    static let transientMarkers: Set<String> = [
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
    ]

    /// Markers for secrets, as set by password managers.
    static let confidentialMarkers: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "com.agilebits.onepassword",
    ]

    static let plainTextTypes: Set<String> = [plainText, utf16ExternalText, utf16Text]
    static let formattedTextTypes: Set<String> = [rtf, rtfd, html]

    /// Image encodings, best first. Compact originals come before PNG and bulky TIFF; GIF
    /// leads because it is the only one that can be animated.
    static let imagePreference = [
        "com.compuserve.gif", "public.png", "public.jpeg", "public.heic", "public.heif",
        "org.webmproject.webp", "public.avif", tiff, "com.microsoft.bmp", pdf,
    ]

    /// Encodings that store raw pixels. They are kept as PNG instead.
    static let uncompressedImageTypes: Set<String> = [tiff, "com.microsoft.bmp"]

    public static func isImage(_ identifier: String) -> Bool {
        if imagePreference.contains(identifier) { return true }
        // Dynamic and legacy identifiers never describe an image we can decode.
        guard identifier.hasPrefix("public.") || identifier.hasPrefix("com."),
              let type = UTType(identifier)
        else { return false }
        return type.conforms(to: .image)
    }

    /// The image type to keep when an app offers the same picture in several encodings.
    static func bestImage(in types: [String]) -> String? {
        imagePreference.first(where: types.contains) ?? types.first(where: isImage)
    }

    /// Apps that put a picture of the selection next to the text they copy. For these the
    /// text is what the user means.
    static let documentApps: Set<String> = [
        "com.microsoft.Excel", "com.microsoft.Word", "com.microsoft.Powerpoint", "com.microsoft.onenote.mac",
        "com.apple.iWork.Numbers", "com.apple.iWork.Pages", "com.apple.iWork.Keynote",
        "com.apple.Numbers", "com.apple.Pages", "com.apple.Keynote", "org.libreoffice.script",
    ]
}
